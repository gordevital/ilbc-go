#!/usr/bin/env python3
"""Generate ilbcfix Go tables from WebRTC libilbc constants.c.

Usage: gen_tables.py constants.c > tables_gen.go
Handles one-line and multi-line flat arrays, plus the two 2-D arrays
(kSearchRange, kEnhPolyPhaser) and the kGain pointer table (emitted as a
slice of slices in declaration order).
"""
import re
import sys

src = open(sys.argv[1]).read()
# Strip C comments.
src = re.sub(r"/\*.*?\*/", "", src, flags=re.S)
src = re.sub(r"//[^\n]*", "", src)

# Normalize.
src = re.sub(r"\s+", " ", src)
src = src.replace("WEBRTC_SPL_WORD32_MAX", "2147483647")

TYPE_MAP = {"int16_t": "int16", "int32_t": "int32", "size_t": "int"}
decls = re.findall(
    r"const\s+(int16_t|int32_t|size_t)\s+(WebRtcIlbcfix_\w+)\s*\[([^\]]*)\]\s*(?:\[[^\]]*\])?\s*=\s*\{(.*?)\};",
    src,
)

ptr_table = re.search(
    r"const\s+int16_t\s*\*\s*const\s+(WebRtcIlbcfix_kGain)\[\d+\]\s*=\s*\{(.*?)\};", src
)

out = []
out.append("// Code generated by tools/gen_tables.py from libilbc constants.c; DO NOT EDIT.")
out.append("package ilbcfix")
out.append("")

def strip_ws(v):
    return v.strip()

for typ, name, dim, body in decls:
    body = body.replace("{", " {").replace("}", "} ")
    if "{" in body:  # 2-D array
        rows = re.findall(r"\{([^}]*)\}", body)
        n = len(rows)
        cells = [int(x.strip()) for x in rows[0].split(",") if x.strip()]
        goname = name[len("WebRtcIlbcfix_"):]
        typgo = TYPE_MAP[typ]
        m = len(cells)
        lines = []
        for r in rows:
            vals = ", ".join(x.strip() for x in r.split(",") if x.strip())
            lines.append("\t{%s}," % vals)
        out.append("var %s = [%d][%d]%s{" % (goname, n, m, typgo))
        out.extend(lines)
        out.append("}")
        out.append("")
    else:
        vals = [x.strip() for x in body.split(",") if x.strip()]
        goname = name[len("WebRtcIlbcfix_"):]
        typgo = TYPE_MAP[typ]
        out.append("var %s = [...]%s{" % (goname, typgo))
        for i in range(0, len(vals), 16):
            out.append("\t" + ", ".join(vals[i : i + 16]) + ",")
        out.append("}")
        out.append("")

if ptr_table:
    names = [x.strip() for x in ptr_table.group(2).split(",") if x.strip()]
    entries = ", ".join(n[len("WebRtcIlbcfix_"):] + "[:]" for n in names)
    out.append("var kGain = [3][]int16{%s}" % entries)

print("\n".join(out))
